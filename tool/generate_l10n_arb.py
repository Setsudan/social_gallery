PLACEHOLDER_TYPES = {
    "error": "String", "count": "int", "days": "int", "limitMb": "int", "size": "String",
    "folderName": "String", "width": "int", "height": "int", "name": "String",
    "done": "int", "moved": "int", "total": "int", "albumName": "String",
    "scanned": "int", "index": "int", "mb": "int", "minutes": "int", "hours": "int",
    "date": "String", "start": "String", "end": "String", "folder": "String",
    "deviceName": "String", "pin": "String", "processed": "int", "relativeTime": "String",
    "detail": "String", "n": "int", "batch": "int", "size": "int",
}


def extract_placeholders(value: str) -> dict:
    import re
    placeholders = {}
    for match in re.finditer(r"\{(\w+)", value):
        name = match.group(1)
        if name == "count" and "plural" in value:
            placeholders[name] = {"type": "int"}
        elif name in PLACEHOLDER_TYPES:
            placeholders[name] = {"type": PLACEHOLDER_TYPES[name]}
        else:
            placeholders[name] = {"type": "String"}
    return placeholders


def build_arb(strings: dict, locale: str | None = None) -> dict:
    arb = {}
    if locale:
        arb["@@locale"] = locale
    for key, value in strings.items():
        arb[key] = value
        if "{" in value and not key.startswith("@"):
            ph = extract_placeholders(value)
            if ph:
                arb[f"@{key}"] = {"placeholders": ph}
    return arb


